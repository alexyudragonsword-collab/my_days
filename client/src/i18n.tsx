// 轻量级双语支持：以中文原文为键，t() 在英文模式下查词典翻译。
// 数据库中存储的业务枚举值（状态、阶段、优先级等）保持中文不变，
// 只在显示层翻译——切换语言不复制、迁移或修改任何业务数据。
// 语言由 SettingsProvider 在渲染子组件前通过 setLang 设定；
// 切换语言时整页重载，因此组件可直接使用模块级 t()。

export type Lang = 'zh' | 'en';

let currentLang: Lang = 'zh';

export function setLang(lang: Lang): void {
  currentLang = lang;
}

export function getLang(): Lang {
  return currentLang;
}

/** 翻译中文原文；支持 {0} {1} 占位符 */
export function t(zh: string, ...args: (string | number)[]): string {
  let out = currentLang === 'en' ? DICT[zh] ?? zh : zh;
  args.forEach((a, i) => {
    out = out.replace(`{${i}}`, String(a));
  });
  return out;
}

export function fmtMinutesI18n(min: number | null | undefined): string {
  if (!min) return '';
  if (currentLang === 'en') {
    if (min < 60) return `${min} min`;
    const h = Math.floor(min / 60);
    const m = min % 60;
    return m ? `${h} h ${m} min` : `${h} h`;
  }
  if (min < 60) return `${min}分钟`;
  const h = Math.floor(min / 60);
  const m = min % 60;
  return m ? `${h}小时${m}分钟` : `${h}小时`;
}

export const WEEKDAY_NAMES = {
  zh: ['日', '一', '二', '三', '四', '五', '六'],
  en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
};

export function weekdayName(dayIndex: number): string {
  const names = WEEKDAY_NAMES[currentLang];
  return currentLang === 'zh' ? `周${names[dayIndex]}` : names[dayIndex];
}

/** 训练模板存储的星期字符（一…日）→ 当前语言的显示名 */
export function weekdayCharLabel(ch: string): string {
  if (currentLang === 'zh') return `周${ch}`;
  const idx = ['日', '一', '二', '三', '四', '五', '六'].indexOf(ch);
  return idx >= 0 ? WEEKDAY_NAMES.en[idx] : ch;
}

